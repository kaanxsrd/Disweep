import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DESCRIPTION = "Sweep your Discord messages. Review it first.";
const DEFAULT_REPOSITORY = "kaanxsrd/Disweep";
const LICENSE = "GPL-3.0-only";

export function parseChecksums(text: string): Map<string, string> {
  const sums = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = /^(\S+)\s+\*?(.+)$/.exec(line.trim());
    if (match?.[1] && match[2]) sums.set(match[2].trim(), match[1]);
  }
  return sums;
}

function digest(sums: Map<string, string>, name: string): string {
  const hash = sums.get(name);
  if (!hash) throw new Error(`checksums.txt has no entry for ${name}`);
  return hash;
}

export function homebrewCask(
  version: string,
  sums: Map<string, string>,
  repository: string,
): string {
  const base = `https://github.com/${repository}/releases/download/v#{version}`;
  const stanza = (arch: string) =>
    `    sha256 "${digest(sums, `disweep_${version}_darwin_${arch}.zip`)}"\n` +
    `    url "${base}/disweep_#{version}_darwin_${arch}.zip"\n`;

  return [
    "# Generated by scripts/package-managers.ts in the Disweep repository. Do not edit.",
    'cask "disweep" do',
    `  version "${version}"`,
    "",
    "  on_arm do",
    stanza("arm64").trimEnd(),
    "  end",
    "  on_intel do",
    stanza("amd64").trimEnd(),
    "  end",
    "",
    '  name "Disweep"',
    `  desc "${DESCRIPTION}"`,
    `  homepage "https://github.com/${repository}"`,
    "",
    "  livecheck do",
    '    skip "Auto-generated on release."',
    "  end",
    "",
    '  app "Disweep.app"',
    "",

    "  postflight do",
    '    system_command "/usr/bin/xattr",',
    '                   args: ["-dr", "com.apple.quarantine", "#{appdir}/Disweep.app"]',
    "  end",
    "end",
    "",
  ].join("\n");
}

export function scoopManifest(
  version: string,
  sums: Map<string, string>,
  repository: string,
): string {
  const base = `https://github.com/${repository}/releases/download/v${version}`;
  const architecture = (arch: string) => {
    const name = `disweep_${version}_windows_${arch}.zip`;
    return { url: `${base}/${name}`, hash: digest(sums, name) };
  };
  const manifest = {
    version,
    architecture: { "64bit": architecture("amd64"), arm64: architecture("arm64") },
    bin: "disweep.exe",
    shortcuts: [["disweep.exe", "Disweep"]],
    homepage: `https://github.com/${repository}`,
    license: LICENSE,
    description: DESCRIPTION,
  };
  return `${JSON.stringify(manifest, null, 4)}\n`;
}

function main(args: string[]): number {
  const [version, checksums, output] = args;
  if (!version || !checksums || !output) {
    console.error("Usage: bun scripts/package-managers.ts VERSION CHECKSUMS OUTPUT_DIR");
    return 2;
  }
  const sums = parseChecksums(readFileSync(checksums, "utf8"));
  const repository = process.env.GITHUB_REPOSITORY ?? DEFAULT_REPOSITORY;
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, "disweep.rb"), homebrewCask(version, sums, repository));
  writeFileSync(join(output, "disweep.json"), scoopManifest(version, sums, repository));
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
